import XCTest
import AppKit
import SwiftUI
@testable import ClipDock
import ClipDockCore

final class ClipboardIntegrationTests: XCTestCase {
    @MainActor
    private func fixture(_ body: (ClipboardStore, ClipboardMonitor, ActiveApplicationMonitor, NSPasteboard) throws -> Void) throws {
        let directory = FileManager.default.temporaryDirectory.appendingPathComponent("clipdock-test-" + UUID().uuidString)
        let store = ClipboardStore(directory: directory)
        let active = ActiveApplicationMonitor(observeWorkspace: false)
        active.applicationDidChange(to: "test.editor")
        let board = NSPasteboard(name: .init("com.clipdock.test." + UUID().uuidString))
        let monitor = ClipboardMonitor(store: store, active: active, pasteboard: board)
        defer {
            monitor.stop(); store.prepareForTermination(); board.releaseGlobally()
            try? FileManager.default.removeItem(at: directory)
        }
        try body(store, monitor, active, board)
    }
    @MainActor
    func testRealPasteboardCaptureDuplicateSearchAndCopy() throws {
        try fixture { store, monitor, _, board in
            board.clearContents(); board.setString("https://apple.com", forType: .string)
            monitor.poll(); monitor.poll()
            XCTAssertEqual(store.history.items.count, 1)
            let item = try XCTUnwrap(store.history.items.first)
            XCTAssertEqual(item.type, .url)
            XCTAssertEqual(store.history.search("APPLE").count, 1)
            store.togglePin(item)
            board.clearContents(); board.setString("second value", forType: .string)
            monitor.poll()
            XCTAssertTrue(monitor.copy(item))
            XCTAssertEqual(board.string(forType: .string), "https://apple.com")
            monitor.poll()
            XCTAssertEqual(store.history.items.count, 2)
            store.clear()
            XCTAssertEqual(store.history.items.count, 1)
            store.flush()
            let loaded = ClipboardStore(directory: store.storage.directory)
            XCTAssertEqual(loaded.history.items.first?.id, item.id)
            XCTAssertEqual(loaded.history.items.first?.isPinned, true)
            loaded.prepareForTermination()
        }
    }
    @MainActor
    func testConcealedTransientAndDisabledCapture() throws {
        try fixture { store, monitor, _, board in
            for marker in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"] {
                board.clearContents()
                board.setString("sensitive fixture", forType: .string)
                board.setData(Data(), forType: .init(marker))
                monitor.poll()
            }
            XCTAssertTrue(store.history.items.isEmpty)
            store.settings.historyEnabled = false
            board.clearContents(); board.setString("disabled fixture", forType: .string); monitor.poll()
            store.settings.historyEnabled = true; monitor.poll()
            XCTAssertTrue(store.history.items.isEmpty)
        }
    }
    @MainActor
    func testExclusionAcrossApplicationSwitchBeforePoll() throws {
        try fixture { store, monitor, active, board in
            store.settings.excludedBundleIDs = ["test.passwords"]
            active.applicationDidChange(to: "test.passwords")
            board.clearContents(); board.setString("secret fixture", forType: .string)
            active.applicationDidChange(to: "test.editor")
            monitor.poll()
            XCTAssertTrue(store.history.items.isEmpty)
            board.clearContents(); board.setString("public fixture", forType: .string)
            monitor.poll()
            XCTAssertEqual(store.history.items.map(\.content), ["public fixture"])
        }
    }
    @MainActor
    func testFileReferencesAndOversizeText() throws {
        try fixture { store, monitor, _, board in
            board.clearContents(); board.writeObjects([NSURL(fileURLWithPath: "/tmp/clipdock-fixture.txt")])
            monitor.poll()
            let item = try XCTUnwrap(store.history.items.first)
            XCTAssertEqual(item.files, ["/tmp/clipdock-fixture.txt"])
            XCTAssertTrue(monitor.copy(item))
            let urls = board.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL]
            XCTAssertEqual(urls?.first?.path, "/tmp/clipdock-fixture.txt")
            board.clearContents(); board.setString(String(repeating: "x", count: 1_024 * 1_024 + 1), forType: .string)
            monitor.poll()
            XCTAssertEqual(store.history.items.count, 1)
            XCTAssertNotNil(store.errorMessage)
        }
    }
    @MainActor
    func testCopyMissingImageLeavesClipboardIntact() throws {
        try fixture { store, monitor, _, board in
            board.clearContents(); board.setString("existing", forType: .string)
            let item = ClipboardItem(type: .image, content: "missing", imageName: "missing.png")
            XCTAssertFalse(monitor.copy(item))
            XCTAssertEqual(board.string(forType: .string), "existing")
            XCTAssertNotNil(store.errorMessage)
        }
    }
    func testImageDownsamplingAndInvalidInput() throws {
        XCTAssertNil(ImageUtilities.normalizedPNG(Data("not an image".utf8)))
        let bitmap = try XCTUnwrap(NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: 3_000, pixelsHigh: 100, bitsPerSample: 8, samplesPerPixel: 4, hasAlpha: true, isPlanar: false, colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0))
        let png = try XCTUnwrap(bitmap.representation(using: .png, properties: [:]))
        let normalized = try XCTUnwrap(ImageUtilities.normalizedPNG(png))
        let result = try XCTUnwrap(NSBitmapImageRep(data: normalized))
        XCTAssertEqual(result.pixelsWide, 2_048)
        XCTAssertLessThan(result.pixelsHigh, 100)
    }
    @MainActor
    func testSystemClipboardExpiryAndNewerValueProtection() throws {
        try fixture { store, monitor, _, board in
            store.settings.retentionSeconds = 300; store.settings.clearSystemClipboard = true
            board.clearContents(); board.setString("owned", forType: .string); monitor.poll()
            monitor.expireSystemClipboard(now: Date().addingTimeInterval(301))
            XCTAssertNil(board.string(forType: .string))
            board.clearContents(); board.setString("next captured", forType: .string); monitor.poll()
            board.clearContents(); board.setString("newer external content", forType: .string)
            monitor.expireSystemClipboard(now: Date().addingTimeInterval(301))
            XCTAssertEqual(board.string(forType: .string), "newer external content")
        }
    }
    @MainActor
    func testClipboardExpiryOffByDefault() throws {
        try fixture { store, monitor, _, board in
            store.settings.retentionSeconds = 300
            board.clearContents(); board.setString("keep system clipboard", forType: .string); monitor.poll()
            monitor.expireSystemClipboard(now: Date().addingTimeInterval(1000))
            XCTAssertEqual(board.string(forType: .string), "keep system clipboard")
        }
    }
    @MainActor
    func testNativeDragPayloadsPreserveTextFilesAndImageFormats() throws {
        try fixture { store, _, _, board in
            let text = ClipboardItem(type: .text, content: "  line one\nline two 🧪")
            board.clearContents(); board.writeObjects(try ClipboardTransfer.writers(for: text, imageURL: nil))
            XCTAssertEqual(board.string(forType: .string), text.content)
            let files = ClipboardItem(type: .file, content: "two", files: ["/tmp/one.txt", "/tmp/two.txt"])
            board.clearContents(); board.writeObjects(try ClipboardTransfer.writers(for: files, imageURL: nil))
            let urls = board.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL]
            XCTAssertEqual(urls?.map(\.path), files.files)
            let bitmap = try XCTUnwrap(NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: 2, pixelsHigh: 2, bitsPerSample: 8, samplesPerPixel: 4, hasAlpha: true, isPlanar: false, colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0))
            let data = try XCTUnwrap(bitmap.representation(using: .png, properties: [:]))
            let url = store.storage.imagesDirectory.appendingPathComponent("drag.png")
            store.flush(); try data.write(to: url)
            let image = ClipboardItem(type: .image, content: "test image", imageName: "drag.png")
            board.clearContents(); board.writeObjects(try ClipboardTransfer.writers(for: image, imageURL: url, includeImageFile: true))
            XCTAssertEqual(board.data(forType: .png), data)
            XCTAssertEqual(board.string(forType: .fileURL), url.absoluteString)
        }
    }
    @MainActor
    func testExpiryPersistsAndReclaimsImage() throws {
        try fixture { store, _, _, _ in
            let item = ClipboardItem(type: .image, content: "expired", imageName: "expired.png", imageBytes: 3, createdAt: Date().addingTimeInterval(-1000))
            store.insert(item, imageData: Data([1, 2, 3])); store.flush()
            XCTAssertTrue(FileManager.default.fileExists(atPath: store.storage.imageURL("expired.png")!.path))
            store.settings.retentionSeconds = 300; store.flush()
            XCTAssertTrue(store.history.items.isEmpty)
            XCTAssertFalse(FileManager.default.fileExists(atPath: store.storage.imageURL("expired.png")!.path))
            XCTAssertTrue(try XCTUnwrap(store.storage.load()).items.isEmpty)
        }
    }

    @MainActor
    func testExpiredImageRemainsAvailableDuringDragAndReceiverGracePeriod() throws {
        try fixture { store, _, _, _ in
            let now = Date()
            let item = ClipboardItem(type: .image, content: "dragged", imageName: "dragged.png", imageBytes: 3, createdAt: now.addingTimeInterval(-1000))
            store.insert(item, imageData: Data([1, 2, 3])); store.flush()
            store.protectImageForDrag(item)
            store.settings.retentionSeconds = 300; store.flush()
            XCTAssertTrue(store.history.items.isEmpty)
            let path = store.storage.imageURL("dragged.png")!.path
            XCTAssertTrue(FileManager.default.fileExists(atPath: path))
            store.finishDraggingImage(item, now: now)
            store.expireHistory(now: now.addingTimeInterval(59)); store.flush()
            XCTAssertTrue(FileManager.default.fileExists(atPath: path))
            store.expireHistory(now: now.addingTimeInterval(60)); store.flush()
            XCTAssertFalse(FileManager.default.fileExists(atPath: path))
        }
    }
    @MainActor
    func testDragSourceDoesNotActivateOnUnpairedMouseUp() throws {
        let view = DragView(content: Text("Test"))
        view.frame = NSRect(x: 0, y: 0, width: 100, height: 50)
        var activated = 0
        view.activate = { activated += 1 }
        let up = try XCTUnwrap(NSEvent.mouseEvent(with: .leftMouseUp, location: NSPoint(x: 10, y: 10), modifierFlags: [], timestamp: 0, windowNumber: 0, context: nil, eventNumber: 1, clickCount: 1, pressure: 0))
        view.mouseUp(with: up)
        XCTAssertEqual(activated, 0)
        XCTAssertTrue(view.accessibilityPerformPress())
        XCTAssertEqual(activated, 1)
    }

}
