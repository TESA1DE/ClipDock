import AppKit
#if SWIFT_PACKAGE
import ClipDockCore
#endif

@MainActor
final class ClipboardMonitor {
    private let store: ClipboardStore
    private let active: ActiveApplicationMonitor
    private let pasteboard: NSPasteboard
    private var timer: Timer?
    private var changeCount: Int
    private var generation = 0
    private var ownedClipboard: (count: Int, date: Date)?
    private let imageQueue = DispatchQueue(label: "com.clipdock.image", qos: .utility)
    private var processingImage = false
    private let privateTypes = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]

    init(store: ClipboardStore, active: ActiveApplicationMonitor, pasteboard: NSPasteboard = .general) {
        self.store = store; self.active = active; self.pasteboard = pasteboard; changeCount = pasteboard.changeCount
        active.didActivate = { [weak self] previous in
            guard let self else { return }
            if self.isExcluded || previous.map(self.store.settings.excludedBundleIDs.contains) == true { self.invalidatePendingCapture() }
        }
    }
    private var isExcluded: Bool { active.bundleIdentifier.map(store.settings.excludedBundleIDs.contains) ?? false }
    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.6, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer?.tolerance = 0.2
    }
    func stop() { timer?.invalidate(); timer = nil; generation += 1 }
    func invalidatePendingCapture() { generation += 1; changeCount = pasteboard.changeCount }
    func expireSystemClipboard(now: Date = Date()) {
        guard store.settings.clearSystemClipboard, store.settings.retentionSeconds > 0,
              let owned = ownedClipboard, now.timeIntervalSince(owned.date) >= store.settings.retentionSeconds else { return }
        defer { ownedClipboard = nil }
        guard pasteboard.changeCount == owned.count else { return }
        pasteboard.clearContents()
        changeCount = pasteboard.changeCount
    }
    func poll() {
        expireSystemClipboard()
        guard store.settings.historyEnabled, !isExcluded else { invalidatePendingCapture(); return }
        guard !processingImage, changeCount != pasteboard.changeCount else { return }
        changeCount = pasteboard.changeCount
        ownedClipboard = nil
        guard !privateTypes.contains(where: { pasteboard.types?.contains(NSPasteboard.PasteboardType($0)) == true }) else { return }
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            let paths = urls.map(\.path)
            store.insert(ClipboardItem(type: .file, content: paths.joined(separator: "\n"), files: paths)); ownedClipboard = (changeCount, Date()); return
        }
        if let data = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff) {
            guard data.count <= 32 * 1_024 * 1_024 else { store.errorMessage = "This image is too large for history (32 MB input limit). Your clipboard is unchanged."; return }
            processingImage = true
            let captureGeneration = generation
            let capturedCount = changeCount
            let capturedAt = Date()
            imageQueue.async { [weak self] in
                let normalized = ImageUtilities.normalizedPNG(data)
                Task { @MainActor [weak self] in
                    guard let self else { return }
                    self.processingImage = false
                    guard self.generation == captureGeneration, self.store.settings.historyEnabled else { return }
                    guard let normalized else { self.store.errorMessage = "This image could not be added to history. Your clipboard is unchanged."; return }
                    let hash = ClipboardItem.digest(normalized)
                    let item = ClipboardItem(type: .image, content: "Copied image", imageName: hash + ".png", imageBytes: normalized.count, imageDigest: hash)
                    self.store.insert(item, imageData: normalized)
                    if self.pasteboard.changeCount == capturedCount { self.ownedClipboard = (capturedCount, capturedAt) }
                }
            }
            return
        }
        guard let text = pasteboard.string(forType: .string), !text.isEmpty else { return }
        guard text.utf8.count <= 1_024 * 1_024 else { store.errorMessage = "This text exceeds the 1 MB history limit. Your clipboard is unchanged."; return }
        let type = ClipboardTypeDetector.detect(text)
        store.insert(ClipboardItem(type: type, content: text))
        ownedClipboard = (changeCount, Date())
    }
    @discardableResult func copy(_ item: ClipboardItem) -> Bool {
        store.flush()
        let objects: [NSPasteboardWriting]
        do { objects = try ClipboardTransfer.writers(for: item, imageURL: store.imageURL(for: item)) }
        catch { store.errorMessage = "This saved image is unavailable."; return false }
        pasteboard.clearContents()
        let success = pasteboard.writeObjects(objects)
        changeCount = pasteboard.changeCount
        if success { ownedClipboard = (changeCount, Date()) }
        if !success { store.errorMessage = "The item could not be copied. Please try again." }
        return success
    }
}
